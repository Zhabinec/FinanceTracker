import { test, expect } from '@playwright/test'
import { financialApp } from './fixtures/financialApp'

test('branded currency list supports keyboard selection, Escape and outside dismissal', async ({ page }) => {
  await financialApp(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const trigger = page.getByRole('combobox', { name: 'Валюта отображения', exact: true })
  await trigger.click()
  await expect(page.getByRole('listbox', { name: 'Валюты' })).toBeVisible()
  await page.screenshot({ path: 'test-results/branded-currency-mobile.png', animations: 'disabled' })
  await trigger.press('ArrowDown')
  await trigger.press('Enter')
  await expect(trigger).toHaveText('USD')
  await expect(page.locator('.dashboard-metrics .expense')).toContainText('1,00')
  await expect(trigger).toBeFocused()
  await trigger.click(); await trigger.press('ArrowDown'); await trigger.press('Escape')
  await expect(trigger).toHaveText('USD')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await trigger.click(); await page.getByRole('heading', { name: 'Обзор финансов', exact: true }).click()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
})

test('calendar handles leap days, keyboard movement, month selection and focus restoration', async ({ page }) => {
  await financialApp(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.locator('.dashboard-period > summary').click()
  const input = page.getByLabel('С даты', { exact: true })
  await input.fill('')
  await input.pressSequentially('28022024')
  await expect(input).toHaveValue('28.02.2024')
  const opener = page.getByRole('button', { name: 'Открыть календарь: С даты', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Календарь: С даты', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('gridcell', { name: /28 февраля 2024/ })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(dialog.getByRole('gridcell', { name: /29 февраля 2024/ })).toBeFocused()
  await page.screenshot({ path: 'test-results/branded-calendar-mobile.png', animations: 'disabled' })
  await page.keyboard.press('Enter')
  await expect(dialog).not.toBeVisible()
  await expect(input).toHaveValue('29.02.2024')
  await expect(opener).toBeFocused()
  await opener.click(); await page.keyboard.press('Escape')
  await expect(input).toHaveValue('29.02.2024')
  await expect(opener).toBeFocused()
  await input.fill('31.02.2024'); await input.press('Tab')
  await expect(input).toHaveAttribute('aria-invalid', 'true')
  await opener.click()
  await dialog.getByRole('button', { name: 'Выбрать месяц и год', exact: true }).click()
  await dialog.getByLabel('Год', { exact: true }).fill('2028')
  await dialog.getByLabel('Год', { exact: true }).press('Tab')
  await dialog.getByRole('button', { name: 'Март', exact: true }).click()
  await dialog.getByRole('gridcell', { name: /^1 марта 2028/ }).click()
  await expect(input).toHaveValue('01.03.2028')
  await expect(input).not.toHaveAttribute('aria-invalid', 'true')
  const monthOpener = page.getByRole('button', { name: 'Открыть календарь: Месяц бюджета', exact: true })
  await monthOpener.click()
  const months = page.getByRole('dialog', { name: 'Календарь: Месяц бюджета', exact: true })
  await months.getByRole('button', { name: 'Март', exact: true }).click()
  await expect(page.getByLabel('Месяц бюджета', { exact: true })).toHaveValue(/03\.\d{4}/)
  await expect(monthOpener).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('editing an invalid date cannot silently save the previous financial date', async ({ page }) => {
  const app = await financialApp(page)
  const savedDates: string[] = []
  await page.route('**/api/finance/transactions/*', route => {
    const body = route.request().postDataJSON()
    savedDates.push(body.occurredOn)
    return route.fulfill({ json: { ...app.transactions[0], ...body } })
  })
  await page.goto('/transactions')
  const row = page.locator('.transaction-row').first()
  await row.getByRole('button', { name: 'Изменить', exact: true }).click()
  await row.getByLabel('Дата', { exact: true }).fill('31.02.2024')
  await row.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(row.getByLabel('Дата', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  expect(savedDates).toEqual([])
  await row.getByLabel('Дата', { exact: true }).fill('29.02.2024')
  await row.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect.poll(() => savedDates).toEqual(['2024-02-29'])
})
